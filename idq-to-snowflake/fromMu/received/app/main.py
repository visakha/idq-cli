"""TRS Compare API: bump Snowflake ETL results against daily IDQ ETL results.

Operator flow (see USER_GUIDE.md for the full story):
  1. Check by hand that the production IDQ ETL has completed.
  2. POST /runs/copy    -- Oracle -> Snowflake.
  3. POST /runs/etl     -- Snowflake ETL in TRS_ETL_WRK.
  4. POST /runs/compare -- IDQ (DATA_SOURCE='IDQ') vs Snowflake (DATA_SOURCE='SNOWFLAKE') in TRS_ETL_WRK, by
     domain and dimension, with spine coverage.
  5. GET /runs/{id}     -- status and messages for any step.

Run with:  uvicorn app.main:app --reload
Docs at:   http://localhost:8000/docs

Swagger UI is served LOCALLY, not from a CDN.  FastAPI's default
/docs page loads its JavaScript and CSS from unpkg/jsdelivr, which
fails on a network that blocks external CDNs (and is a needless
external dependency for an internal operator tool).  So the
default docs are turned off (docs_url=None, and redoc_url=None --
ReDoc is CDN-based too), and /docs is re-implemented below with
the JS/CSS mounted from the swagger-ui-bundle package installed
alongside the app (see requirements.txt).  /openapi.json is
unaffected -- it is generated by FastAPI itself, not by Swagger UI.

Structure (see USER_GUIDE.md, "How this project is laid out"):
  app/core/    -- config, engines (lazy factories, no ORM)
  app/domain/  -- catalog, explicit table definitions, Pydantic models
  app/repositories/ -- Oracle, Snowflake, Run repositories + named SQL
  app/services/-- copy, ETL, compare (orchestration only, repos injected)
  app/api/     -- FastAPI routes (thin) + Depends providers
"""

from __future__ import annotations

from fastapi import FastAPI
from fastapi.openapi.docs import get_swagger_ui_html
from fastapi.openapi.utils import get_openapi
from fastapi.staticfiles import StaticFiles

try:
    from swagger_ui_bundle import swagger_ui_path
except ImportError as exc:  # pragma: no cover - dependency is in requirements.txt
    raise RuntimeError(
        "swagger-ui-bundle is required to serve /docs locally. "
        "Install it with: pip install swagger-ui-bundle "
        "(or: pip install -r requirements.txt)"
    ) from exc

from app.api.routes import router

app = FastAPI(
    title="TRS Compare API",
    description=(
        "Copy Oracle IDQ sources and targets to Snowflake, run the "
        "Snowflake ETL, and compare IDQ targets against Snowflake "
        "targets by domain, dimension and spine."
    ),
    version="5.4.0",
    docs_url=None,   # default CDN docs off; see /docs below
    redoc_url=None,  # ReDoc is CDN-based too; no /redoc endpoint
)


def custom_openapi():
    """Serve /openapi.json as OpenAPI 3.0.3, not FastAPI's default 3.1.0.

    Why this exists: swagger-ui-bundle's latest release (1.1.0)
    bundles Swagger UI 4.15.5, which only renders `swagger: "2.0"`
    and `openapi: 3.0.n` definitions.  FastAPI generates
    `openapi: 3.1.0` by default, so the bundled UI refuses the
    whole spec with "Unable to render this definition / The
    provided definition does not specify a valid version field"
    -- even though the spec itself is fine.  There is no newer
    swagger-ui-bundle release to upgrade to, and switching to
    the CDN UI would defeat the offline point of bundling, so
    the spec is emitted as 3.0.3 instead.  Nothing else changes:
    get_openapi with openapi_version="3.0.3" builds the same
    paths, schemas and security schemes; the only 3.1-only
    constructs to watch for are `const`, `prefixItems` and
    type-arrays, and this API's spec contains none of them
    (its optionals use `anyOf`, which is valid in 3.0).
    If the bundle ever ships Swagger UI 5, delete this function
    and FastAPI's default 3.1.0 spec will work as-is.
    """
    if app.openapi_schema:
        return app.openapi_schema
    app.openapi_schema = get_openapi(
        title=app.title,
        version=app.version,
        description=app.description,
        routes=app.routes,
        openapi_version="3.0.3",
    )
    return app.openapi_schema


app.openapi = custom_openapi

# Mount the static assets directory from the swagger-ui-bundle
# package directly: /swagger-static/swagger-ui-bundle.js and
# /swagger-static/swagger-ui.css, served by this server.
app.mount("/swagger-static", StaticFiles(directory=swagger_ui_path), name="swagger-static")

app.include_router(router)


@app.get("/docs", include_in_schema=False)
async def custom_swagger_ui_html():
    """Swagger UI page, with its JS/CSS served locally (no CDN)."""
    return get_swagger_ui_html(
        openapi_url=app.openapi_url,
        title=app.title + " - Swagger UI",
        swagger_js_url="/swagger-static/swagger-ui-bundle.js",
        swagger_css_url="/swagger-static/swagger-ui.css",
    )

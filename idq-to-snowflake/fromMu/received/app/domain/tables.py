def table_for(name: str, schema: str) -> Table:
    """Build an explicit Table for `name` in `schema`.

    A fresh Table (and fresh Columns) is built on every call,
    so the same table name can be used in several schemas
    in one process without sharing Column objects.
    """
    if name not in COLUMN_TYPES:
        raise KeyError(f"Unknown table: {name!r}. See app/domain/catalog.py.")
    return Table(
        name,
        MetaData(),
        *(Column(col, typ) for col, typ in COLUMN_TYPES[name]),
        schema=schema,
    )


def column_names(name: str) -> list[str]:
    """Column names for `name`, in DDL order."""
    return [col for col, _typ in COLUMN_TYPES[name]]

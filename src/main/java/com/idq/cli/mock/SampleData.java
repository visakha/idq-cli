package com.idq.cli.mock;

import com.idq.cli.config.EtlSettings;
import com.idq.cli.core.audit.MockDataGenerated;
import com.idq.cli.workflow.DatabaseBootstrap;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.util.List;
import java.util.Optional;
import java.util.stream.Stream;
import org.springframework.context.ApplicationEventPublisher;
import org.springframework.stereotype.Component;

/// Entry point of `fill-sample-mock-data` / `fill-sample-real-data`: resolves and invokes the function
/// `fill_sample_mock_data_<mapping>` (or `fill_sample_real_data_<mapping>`) of the mapping's source generator.
///
/// The statements of every mock fill are published as [MockDataGenerated] for the audit reports.
@Component
public class SampleData {

    public static final String MOCK_PREFIX = "fill_sample_mock_data_";
    public static final String REAL_PREFIX = "fill_sample_real_data_";

    private final List<Object> generators;
    private final ReferenceMockData reference;
    private final DatabaseBootstrap bootstrap;
    private final EtlSettings settings;
    private final MockTables tables;
    private final ApplicationEventPublisher events;

    public SampleData(TrsMockData trs, EciMockData eci, ViewMockData views, CreMockData cre, RealSampleData real,
            ReferenceMockData reference, DatabaseBootstrap bootstrap, EtlSettings settings, MockTables tables,
            ApplicationEventPublisher events) {
        this.generators = List.of(trs, eci, views, cre, real);
        this.reference = reference;
        this.bootstrap = bootstrap;
        this.settings = settings;
        this.tables = tables;
        this.events = events;
    }

    public String fillMock(String mapping) {
        if (!settings.mockData()) {
            return "mock_data=false: mock data generation is disabled";
        }
        var function = MOCK_PREFIX + mapping;
        var method = find(function).orElseThrow(() -> new IllegalArgumentException("No function " + function));
        var created = bootstrap.createMissingObjects();
        recorded(MockDataGenerated.REFERENCE_DATA, reference::seed);
        recorded(mapping, () -> invoke(method));
        return "%s: %d rows per table generated%s".formatted(function, settings.mockRowsPerTable(),
                created.isEmpty() ? "" : " (created missing tables " + created + ")");
    }

    /// `fill_sample_mock_data_<mapping>` for every given mapping, as `run-etl` does when `mock_data=true`.
    public String fillMockAll(List<String> mappings) {
        if (!settings.mockData()) {
            return "mock_data=false: source tables are used as they are";
        }
        var functions = mappings.stream().map(mapping -> MOCK_PREFIX + mapping).toList();
        var methods = functions.stream().map(function -> find(function)
                .orElseThrow(() -> new IllegalArgumentException("No function " + function))).toList();
        bootstrap.createMissingObjects();
        recorded(MockDataGenerated.REFERENCE_DATA, reference::seed);
        for (int i = 0; i < methods.size(); i++) {
            var method = methods.get(i);
            recorded(mappings.get(i), () -> invoke(method));
        }
        return "mock_data=true: %d rows per table generated by %s%s".formatted(settings.mockRowsPerTable(),
                String.join(", ", functions), settings.mockDataPrefix().isEmpty() ? ""
                        : " (mock-data-pre-fix=" + settings.mockDataPrefix() + ")");
    }

    public String fillReal(String mapping) {
        var function = REAL_PREFIX + mapping;
        return find(function).map(method -> {
            invoke(method);
            return function + ": done";
        }).orElse(function + ": not implemented yet (placeholder)");
    }

    private void recorded(String group, Runnable fill) {
        events.publishEvent(new MockDataGenerated(group, settings.mockDataPrefix(), tables.record(fill)));
    }
    // todo:comments
    private Optional<Method> find(String function) {
        return generators.stream().flatMap(g -> Stream.of(g.getClass().getMethods()))
                .filter(m -> m.getName().equals(function) && m.getParameterCount() == 0).findFirst();
    }

    private void invoke(Method method) {
        var owner = generators.stream().filter(g -> method.getDeclaringClass().isInstance(g)).findFirst()
                .orElseThrow();
        try {
            method.invoke(owner);
        } catch (IllegalAccessException e) {
            throw new IllegalStateException(e);
        } catch (InvocationTargetException e) {
            throw e.getCause() instanceof RuntimeException runtime ? runtime : new IllegalStateException(e.getCause());
        }
    }
}
